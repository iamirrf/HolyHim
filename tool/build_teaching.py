"""Build identical client/server teaching data; full release gate is --require-complete."""
import argparse, json, subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--require-complete',action='store_true');args=p.parse_args()
data=json.loads((ROOT/'content/teaching.json').read_text());days=set();questions=set()
for lesson in data['lessons']:
 day=lesson['day'];assert day not in days and 1<=day<=365;days.add(day)
 assert all(lesson[k].strip() for k in ['objective','context','takeaway'])
 assert len(lesson['questions'])==2
 for question in lesson['questions']:
  assert question['id'] not in questions;questions.add(question['id'])
  options=question['options'];ids=[o['id'] for o in options]
  assert len(options)==len(set(ids))==len(set(o['text'] for o in options))==4
  assert question['correctOptionId'] in ids and question['explanation'].strip()
  assert question['teachingSource'] in [f'day-{day:03}/understand',f'day-{day:03}/hope']
  assert not any('placeholder' in str(o).lower() for o in options)
if args.require_complete:
 assert days==set(range(1,366)),f'Release blocked: {len(days)}/365 teaching lessons'
 assert len(questions)==730
payload=json.dumps(data,ensure_ascii=False,indent=2)+'\n'
dart="// Generated by tool/build_teaching.py.\nimport 'dart:convert';\nimport 'package:holyher/models/learning.dart';\nconst teachingVersion = '"+data['version']+"';\nfinal teachingCatalog = Map<int,TeachingLesson>.fromEntries((jsonDecode(r'''"+payload+"''')['lessons'] as List).map((v)=>MapEntry(v['day'] as int,TeachingLesson.fromJson(v))));\nclass TeachingLesson {\n final String objective,context,takeaway;\n final List<LessonQuestion> questions;\n TeachingLesson.fromJson(Map<String,dynamic> v): objective=v['objective'],context=v['context'],takeaway=v['takeaway'],questions=[for(final q in v['questions']) LessonQuestion.fromJson(q)];\n}\n"
dart=subprocess.run(['dart','format','--language-version=3.0','--output=show','--summary=none'],input=dart,text=True,capture_output=True,check=True).stdout
for path,text in [(ROOT/'functions/teaching.json',payload),(ROOT/'lib/data/teaching.dart',dart)]:
 if args.check: assert path.read_text()==text,f'Stale {path}'
 else:path.write_text(text)
print(f'Validated {len(days)} teaching lessons / {len(questions)} questions; full-catalog gate {"passed" if len(days)==365 else "NOT passed"}.')
