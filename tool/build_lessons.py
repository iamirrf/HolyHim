"""Build the bundled catalog and source evidence; --check never changes files."""
from __future__ import annotations
import argparse
from collections import Counter
from functools import cache
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SCRIPTURE = ROOT / 'tool/scripture'
CONTENT_PARTS = (ROOT / 'content/lessons_001_183.json', ROOT / 'content/lessons_184_365.json')
PROSE_LIMITS = {'confidence': (20, 35), 'reason': (30, 50), 'hope': (15, 30), 'devotionalReflection': (20, 35), 'reflection': (5, 15)}
FIELDS = {'day', 'title', 'reference', 'theme', *PROSE_LIMITS}
CANONICAL_CODES = set(('GEN EXO LEV NUM DEU JOS JDG RUT 1SA 2SA 1KI 2KI 1CH 2CH EZR NEH EST JOB PSA PRO ECC SNG ISA JER LAM EZK DAN HOS JOL AMO OBA JON MIC NAM HAB ZEP HAG ZEC MAL MAT MRK LUK JHN ACT ROM 1CO 2CO GAL EPH PHP COL 1TH 2TH 1TI 2TI TIT PHM HEB JAS 1PE 2PE 1JN 2JN 3JN JUD REV').split())


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def json_text(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2) + '\n'


@cache
def book_codes() -> dict[str, str]:
    names = {book.attrib['short']: book.attrib['code'] for book in ET.parse(SCRIPTURE / 'book_names.xml').getroot() if book.attrib['code'] in CANONICAL_CODES}
    names['Psalm'] = names.pop('Psalms', 'PSA')
    return names


def verse_keys(reference: str) -> list[str]:
    match = re.fullmatch(r'(.+) ([1-9]\d*):([1-9]\d*)(?:-([1-9]\d*))?', reference)
    if not match:
        raise ValueError(f'Unsupported reference: {reference!r}')
    book, chapter, first, last = match.groups()
    if book not in book_codes():
        raise ValueError(f'Reference is outside the selected 66-book canon: {reference}')
    start, end = int(first), int(last or first)
    if end < start:
        raise ValueError(f'Reversed verse range: {reference}')
    return [f'{book} {chapter}:{number}' for number in range(start, end + 1)]


def passage(reference: str, verses: dict[str, str]) -> str:
    try:
        return ' '.join(verses[key] for key in verse_keys(reference))
    except KeyError as error:
        raise ValueError(f'Missing pinned source verse: {error.args[0]}') from error


def source_url(reference: str) -> str:
    book, chapter, verse = re.fullmatch(r'(.+) (\d+):(\d+)(?:-\d+)?', reference).groups()
    # eBible chapter filenames have two digits, or three for the 150 Psalms.
    chapter_file = chapter.zfill(3 if book == 'Psalm' else 2)
    return f'https://ebible.org/engwebp/{book_codes()[book]}{chapter_file}.htm#V{verse}'


def load_content() -> list[dict]:
    lessons = [lesson for part in CONTENT_PARTS for lesson in read_json(part)]
    if [lesson.get('day') for lesson in lessons] != list(range(1, 366)):
        raise ValueError('Content must contain exactly days 1 through 365 in order')
    for lesson in lessons:
        day = lesson['day']
        if set(lesson) != FIELDS:
            raise ValueError(f'Day {day}: unexpected or missing fields')
        for field in FIELDS - {'day'}:
            text = lesson[field]
            if not isinstance(text, str) or not text.strip() or text != text.strip():
                raise ValueError(f'Day {day}: invalid {field}')
        for field, (minimum, maximum) in PROSE_LIMITS.items():
            count = len(lesson[field].split())
            if not minimum <= count <= maximum:
                raise ValueError(f'Day {day}: {field} has {count} words; expected {minimum}–{maximum}')
        total = sum(len(lesson[field].split()) for field in PROSE_LIMITS)
        if not 110 <= total <= 160:
            raise ValueError(f'Day {day}: total prose has {total} words; expected 110–160')
        verse_keys(lesson['reference'])
    for field in ('title', 'reference', *PROSE_LIMITS):
        duplicates = [text for text, count in Counter(item[field] for item in lessons).items() if count > 1]
        if duplicates:
            raise ValueError(f'Duplicate {field}: {duplicates[0]!r}')
    return lessons


def dart_string(value: str) -> str:
    # JSON handles quotes, backslashes and controls; Dart also interpolates $.
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$').replace('\u2028', r'\u2028').replace('\u2029', r'\u2029')


MODEL = '''// Generated by tool/build_lessons.py. Edit the authored content JSON instead.
// Scripture is verbatim public-domain WEB; devotional prose is original reflection.

/// One daily lesson with Scripture and clearly separate devotional application.
class DailyLesson {
  final String theme;
  final String translation;
  final String devotionalReflection;
  final int day;
  final String title;
  final String verseReference;
  final String verseText;
  final String confidence;
  final String reason;
  final String hope;
  final String reflection;

  const DailyLesson({
    this.theme = 'A little hope',
    this.translation = 'WEB',
    this.devotionalReflection = '',
    required this.day,
    required this.title,
    required this.verseReference,
    required this.verseText,
    required this.confidence,
    required this.reason,
    required this.hope,
    required this.reflection,
  });
}

/// All 365 authored lessons are bundled for offline reading after access validation.
const lessons = <DailyLesson>[
'''
LOOKUP = '''\n];

DailyLesson? lessonForDay(int day) {
  if (day < 1 || day > lessons.length) {
    return null;
  }
  return lessons[day - 1];
}
'''


def render_dart(lessons: list[dict], verses: dict[str, str]) -> str:
    entries = []
    for lesson in lessons:
        fields = {'day': lesson['day'], 'title': lesson['title'], 'theme': lesson['theme'][0].upper() + lesson['theme'][1:], 'translation': 'WEB', 'verseReference': f"{lesson['reference']} (WEB)", 'verseText': passage(lesson['reference'], verses), **{field: lesson[field] for field in PROSE_LIMITS}}
        lines = ['  DailyLesson(']
        lines.extend(f'    {key}: {value if isinstance(value, int) else dart_string(value)},' for key, value in fields.items())
        lines.append('  ),')
        entries.append('\n'.join(lines))
    source = MODEL + '\n'.join(entries) + LOOKUP
    dart = shutil.which('dart')
    if not dart:
        raise RuntimeError('Dart SDK is required to format the generated catalog')
    result = subprocess.run([dart, 'format', '--output=show', '--summary=none'], input=source, text=True, capture_output=True, check=True)
    return result.stdout


def evidence(lessons: list[dict], verses: dict[str, str], provenance: dict) -> list[dict]:
    return [{'day': lesson['day'], 'reference': lesson['reference'], 'translation': 'WEB', 'edition': provenance['edition'], 'source': source_url(lesson['reference']), 'corpusSource': provenance['source'], 'retrieved': provenance['retrieved'], 'archiveSha256': provenance['archiveSha256'], 'textSha256': provenance['textSha256'], 'verseKeys': verse_keys(lesson['reference']), 'verseSha256': sha256(passage(lesson['reference'], verses).encode('utf-8')), 'text': passage(lesson['reference'], verses)} for lesson in lessons]


def audit(lessons: list[dict], provenance: dict) -> dict:
    lengths = [sum(len(lesson[field].split()) for field in PROSE_LIMITS) for lesson in lessons]
    books = Counter(re.fullmatch(r'(.+) \d+:\d+(?:-\d+)?', lesson['reference'])[1] for lesson in lessons)
    quoted = {key for lesson in lessons for key in verse_keys(lesson['reference'])}
    return {
        'lessons': len(lessons), 'firstDay': 1, 'lastDay': 365,
        'uniqueTitles': len({lesson['title'] for lesson in lessons}),
        'uniqueReferences': len({lesson['reference'] for lesson in lessons}),
        'sourceCoverage': {'lessonsWithSource': 365, 'quotedVerseCount': len(quoted), 'selectedBookCount': len(books), 'lessonsByBook': dict(books)},
        'proseWordCount': {'minimum': min(lengths), 'maximum': max(lengths), 'mean': round(sum(lengths) / len(lengths), 1), 'total': sum(lengths)},
        'distinctProseFields': {field: len({lesson[field] for lesson in lessons}) for field in PROSE_LIMITS},
        'wordCountLimits': PROSE_LIMITS,
        'contentSha256': {part.name: sha256(part.read_bytes()) for part in CONTENT_PARTS},
        'scriptureProvenance': provenance,
        'scriptureNormalization': 'Only presentation whitespace and verse-boundary joining; footnotes, cross-references, headings and verse numbers are excluded. Translation words and punctuation are preserved.',
        'devotionalReflection': 'Original first-person literary devotional prose, separate from Scripture. It must be labeled as devotional reflection in the app.',
        'validation': 'Sequence, required fields, per-field and total word counts, distinct titles/references/prose, canonical source coverage. Run tool/verify_scripture.py for independent XML and artifact verification.',
    }


def artifacts() -> dict[Path, str]:
    lessons = load_content()
    verses = read_json(SCRIPTURE / 'verses.json')
    provenance = read_json(SCRIPTURE / 'provenance.json')
    return {ROOT / 'lib/data/lessons.dart': render_dart(lessons, verses), ROOT / 'test/fixtures/scripture.json': json_text(evidence(lessons, verses, provenance)), ROOT / 'content/editorial_report.json': json_text(audit(lessons, provenance))}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated artifacts without writing')
    args = parser.parse_args()
    stale = []
    for path, expected in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding='utf-8')
    if stale:
        print('Stale generated artifacts: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('365 lessons: generated artifacts ' + ('verified' if args.check else 'built'))
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(1)
