"""Generate the offline v2 catalog from one authored source; --check is read-only."""
from pathlib import Path
import argparse, hashlib, json, re
from verify_lessons import validate, passage
ROOT=Path(__file__).resolve().parents[1]; SCRIPTURE=ROOT/'tool/scripture'
def read_json(p):return json.loads(p.read_text())
def sha256(b):return hashlib.sha256(b).hexdigest()
def verse_keys(reference):
 m=re.fullmatch(r'(.+) (\d+):(\d+)(?:-(\d+))?',reference);book,ch,a,b=m.groups();return [f'{book} {ch}:{n}' for n in range(int(a),int(b or a)+1)]
def load_content():return read_json(ROOT/'content/lessons_v2.json')
def dart(s):return json.dumps(s,ensure_ascii=False).replace('$',r'\$')
def artifacts():
 lessons=load_content();verses=read_json(SCRIPTURE/'verses.json');errors=validate(lessons,verses)
 if errors:raise ValueError('\n'.join(errors))
 output="// GENERATED by tool/build_lessons.py. Scripture: public-domain WEB.\nimport '../domain/lesson.dart';\n\nconst lessons = <Lesson>[\n"
 for lesson in lessons:output+='  Lesson('+', '.join(k+': '+(str(v) if k=='day' else dart(v)) for k,v in lesson.items())+'),\n'
 output+='];\n\nconst unitTitles = <String>[' + ', '.join(dart(u['title']) for u in read_json(ROOT/'content/units.json')) + '];\n\nLesson? lessonForDay(int day) => day >= 1 && day <= lessons.length ? lessons[day - 1] : null;\n'
 fixture=[{'day':d['day'],'reference':d['reference'],'text':d['verse'],'verseKeys':verse_keys(d['reference']),'verseSha256':sha256(d['verse'].encode())} for d in lessons]
 art=json.loads((ROOT/'assets/art/library/catalog.json').read_text())['days']
 chapter_manifest=ROOT/'art/chapter-manifest.json'
 chapters=read_json(chapter_manifest)['chapters'] if chapter_manifest.exists() else []
 chapter_art={day:u['id'] for u in chapters if u['assets'] for day in range(u['firstDay'],u['lastDay']+1)}
 widget=[{'day':d['day'],'reference':d['reference'],'verse':d['verse'],
          'artId':chapter_art.get(d['day'],art[d['day']-1])} for d in lessons]
 return {ROOT/'ios/HolyHimWidget/WidgetVerses.json':json.dumps(widget,ensure_ascii=False,separators=(',',':'))+'\n',ROOT/'lib/data/lessons.g.dart':output,ROOT/'test/fixtures/scripture.json':json.dumps(fixture,ensure_ascii=False,indent=2)+'\n',ROOT/'public/lesson-sample.json':json.dumps(lessons[0],ensure_ascii=False,indent=2)+'\n'}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 for path,value in artifacts().items():
  if a.check:
   if not path.exists() or path.read_text()!=value:raise ValueError('Stale generated file: '+str(path))
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value)
 print('365 v2 lessons: generated artifacts '+('verified' if a.check else 'written'))
if __name__=='__main__':main()
