#!/usr/bin/env python3
"""Generate lib/data/chapters.g.dart (chapter titles and one-line summaries)
from content/units.json, for the walk's chapter banners.

  python3 tool/build_chapters.py          # write
  python3 tool/build_chapters.py --check  # fail if the file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNITS = ROOT / 'content/units.json'
OUT = ROOT / 'lib/data/chapters.g.dart'


def render() -> str:
    units = json.loads(UNITS.read_text())
    rows = []
    for n, unit in enumerate(units, 1):
        assert unit['lastDay'] - unit['firstDay'] == 4, unit['id']
        rows.append(f"  Chapter({n}, {json.dumps(unit['title'], ensure_ascii=False)}, "
                    f"{json.dumps(unit['summary'], ensure_ascii=False)}, "
                    f"{unit['firstDay']}, {unit['lastDay']}),")
    return ('// Generated by tool/build_chapters.py from content/units.json. Do not edit.\n'
            'class Chapter {\n'
            '  final int number, firstDay, lastDay;\n'
            '  final String title, summary;\n'
            '  const Chapter(this.number, this.title, this.summary, this.firstDay, this.lastDay);\n'
            '  static Chapter forDay(int day) => chapters[((day - 1) ~/ 5).clamp(0, chapters.length - 1)];\n'
            '}\n\n'
            'const chapters = <Chapter>[\n' + '\n'.join(rows) + '\n];\n')


def main() -> int:
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT.relative_to(ROOT)} is stale; run python3 tool/build_chapters.py')
            return 1
        print('Chapters are current.')
        return 0
    OUT.write_text(text)
    print(f'Wrote {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
