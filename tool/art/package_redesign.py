"""Package inspected, built-in-generated HolyHim artwork. Never calls an API."""
import hashlib,json
from pathlib import Path
from PIL import Image,ImageOps,ImageDraw
ROOT=Path(__file__).resolve().parents[2]
raw=ROOT/'art/generated';dest=ROOT/'assets/art'
prompts=json.loads((ROOT/'art/redesign-prompts.json').read_text())
manifest={'version':3,'generator':'built-in image_gen','library':[],'badges':[]}
for kind in ['library','badges']:
 out=dest/kind;out.mkdir(parents=True,exist_ok=True)
 for job in prompts[kind]:
  source=raw/kind/(job['id']+'.png')
  if not source.exists():continue
  with Image.open(source) as opened:
   image=opened.copy()
  name=job['id']+('.webp' if kind=='library' else '.png')
  target=out/name
  if kind=='library':
   image=ImageOps.fit(image.convert('RGB'),(1024,1536),method=Image.Resampling.LANCZOS)
   image.save(target,'WEBP',quality=86,method=6)
   ImageOps.fit(image,(240,360),method=Image.Resampling.LANCZOS).save(out/(job['id']+'-thumb.webp'),'WEBP',quality=80,method=6)
  else:
   if image.mode!='RGBA' or image.getchannel('A').getextrema()[0]>=255:raise ValueError(f'{source.name}: missing real transparency')
   # Center by alpha bounds, so generated margins cannot vary on the badge shelf.
   box=image.getchannel('A').getbbox(); image=image.crop(box)
   image.thumbnail((820,820),Image.Resampling.LANCZOS)
   canvas=Image.new('RGBA',(1024,1024));canvas.alpha_composite(image,((1024-image.width)//2,(1024-image.height)//2))
   canvas.save(target,optimize=True)
   canvas.resize((240,240),Image.Resampling.LANCZOS).save(out/(job['id']+'-thumb.png'),optimize=True)
  manifest[kind].append({**job,'source':str(source.relative_to(ROOT)),'asset':str(target.relative_to(ROOT)),
   'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
(ROOT/'art/redesign-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
lessons=json.loads((ROOT/'content/lessons_v2.json').read_text());ids=[x['id'] for x in prompts['library']]
groups={'jesus':[x for x in ids if x.startswith('jesus-')],'sky':[x for x in ids if x.startswith('sky-')],
 'cross':[x for x in ids if x.startswith('cross-')],'scripture':[x for x in ids if x.startswith('scripture-')],
 'landscape':[x for x in ids if x.startswith('landscape-') or x.startswith('symbol-')]}
mapping=[]
for lesson in lessons:
 topic=lesson['theme'].lower();reference=lesson['reference']
 if topic in ['prayer','scripture','wisdom','listening','understanding','reflection','teachability','intercession']:group='scripture'
 elif topic in ['peace','rest','hope','comfort','grief','wonder','renewal','longing','refuge','lament']:group='sky'
 elif reference.startswith(('Matthew','Mark','Luke','John')):group='jesus'
 elif topic in ['courage','faith','trust','forgiveness','grace','repentance','perseverance','confidence','security']:group='cross'
 else:group='landscape'
 mapping.append(groups[group][(lesson['day']-1)%len(groups[group])])
(dest/'library/catalog.json').write_text(json.dumps({'version':3,'days':mapping,'subjects':prompts['library']},indent=2)+'\n')
quoted=lambda s:json.dumps(s)
code="// Generated by tool/art/package_redesign.py; see art/redesign-prompts.json.\nimport 'chapter_catalog.g.dart';\n\nabstract final class HolyArtCatalog {\n"
code+='  static const days = <String>[\n'+''.join('    '+quoted(v)+',\n' for v in mapping)+ '  ];\n'
code+="  static String idForDay(int day) => days[(day - 1).clamp(0, days.length - 1)];\n"
code+="  static String? chapterFolderForDay(int day) { final chapter = ChapterCatalog.forDay(day); return chapter?.hasAssets == true ? chapter!.id : null; }\n"
code+="  static String assetForDay(int day) => chapterFolderForDay(day) != null ? 'assets/art/chapters/${chapterFolderForDay(day)}/portrait.webp' : 'assets/art/library/${idForDay(day)}.webp';\n"
code+="  static String thumbnailForDay(int day) => chapterFolderForDay(day) != null ? 'assets/art/chapters/${chapterFolderForDay(day)}/portrait-thumb.webp' : 'assets/art/library/${idForDay(day)}-thumb.webp';\n"
code+="  static String? landscapeForDay(int day) => chapterFolderForDay(day) == null ? null : 'assets/art/chapters/${chapterFolderForDay(day)}/landscape.webp';\n"
code+="  static const scenes = <String,String>{'welcome-peace':'sky-dawn','welcome-minute':'scripture-prayer','welcome-growth':'symbol-olive','onboarding-heart':'sky-stillness','saved-empty':'scripture-morning','growth-empty':'landscape-path','celebration':'sky-rays'};\n}\n"
(ROOT/'lib/design/art_catalog.dart').write_text(code)
for kind in ['library','badges']:
 items=manifest[kind];w,h=(180,270) if kind=='library' else (180,180)
 rows=(len(items)+4)//5
 sheet=Image.new('RGB',(5*w,rows*(h+28)),'#f9f3ee');draw=ImageDraw.Draw(sheet)
 for i,item in enumerate(items):
  image=Image.open(ROOT/item['asset']).convert('RGBA');image.thumbnail((w,h),Image.Resampling.LANCZOS)
  x=i%5*w;y=i//5*(h+28);sheet.paste(image,(x+(w-image.width)//2,y+(h-image.height)//2),image)
  draw.text((x+5,y+h+6),item['id'],fill='#482e39')
 sheet.save(ROOT/f'store/redesign-v3/{kind}-review.jpg',quality=87)
print({kind:len(manifest[kind]) for kind in ['library','badges']})
